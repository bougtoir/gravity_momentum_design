"""Submission package builder: highlights, graphical abstract, cover letter,
supplement docx, editable figures pptx, tables docx, final zip."""
import os, sys, zipfile
import pandas as pd
from docx import Document
from docx.shared import Pt, Inches
from pptx import Presentation
from pptx.util import Inches as PInches

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TAB = os.path.join(ROOT, "results", "tables")
FIG = os.path.join(ROOT, "results", "figures")
MS = os.path.join(ROOT, "manuscript")
SUP = os.path.join(ROOT, "supplement")
SUB = os.path.join(ROOT, "submission")
for d in (SUP, SUB): os.makedirs(d, exist_ok=True)

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from make_manuscript import FIGCAPS, TITLE
from omml import write_rich, pptx_rich

mc = pd.read_csv(os.path.join(TAB, "mc_summary.csv"))
trans = pd.read_csv(os.path.join(TAB, "transitions.csv"))
sens = pd.read_csv(os.path.join(TAB, "sensitivity.csv"))
conv = pd.read_csv(os.path.join(TAB, "convergence.csv"))
inter = pd.read_csv(os.path.join(TAB, "interaction.csv"))
suit = pd.read_csv(os.path.join(TAB, "mc_summary_suit40.csv"))

g_ben_hi = trans.g_benefit50.dropna().max()

HIGHLIGHTS = [
    "Gravity supplies implicit friction stabilization to built interfaces",          # 68
    "Unintended transverse/angular impulse quantified across five interfaces",        # 73
    "Demand grows ~1/g while inertia persists; Γ_T ratio formalizes it",             # 67
    f"Momentum-aware geometry prevents impulse; benefit grows below ~{g_ben_hi:.2f} g",
    "Cross-interface synthesis enables gravity-parameterized topology design",       # 73
]

COVER = f"""Dear Editors,

We submit \"{TITLE}\" for consideration as a Research Paper in Building and
Environment.

The paper treats gravity as an environmental boundary condition of
occupant–building interaction. Terrestrial built environments are implicitly
engineered around the stabilization that gravity supplies for free (normal
force, friction); our mechanical framework quantifies what happens to that
supply as g declines, introduces two cross-interface metrics (unintended
translational and angular impulse, UTI/UAI), and tests — across five
mechanically normalized built-environment interfaces over a continuous
gravity sweep with Monte Carlo uncertainty — whether interface geometry can
prevent impulse generation rather than restrain it afterward.

We believe the work fits the journal's scope on human interaction with the
built environment under varying environmental conditions and on
simulation-driven design. Extraterrestrial habitats serve as the extreme test
case of a general principle; the framework and metrics are directly relevant
to occupant–interface design wherever support mechanics change.

All results are generated by the accompanying open code; a data/code
availability statement is included.

Sincerely,
The authors
"""

SUPP_TEXT = """
S1. Extended Monte Carlo summaries — mc_summary.csv (all case/variant/g* cells,
means and 5–95th percentiles), mc_summary_suit40.csv, mc_summary_suit40_rom.csv.

S2. Design-transition estimates — transitions.csv (exploratory: first g* at
which baseline Γ_T ≥ 1 and where normalized benefit B_UTI ≥ 0.5).

S3. Sensitivity sweep — sensitivity.csv (one-at-a-time, door at g*=0.38).

S4. Convergence diagnostics — convergence.csv (N = 250–4000; MC means stable
within ~5%).

S5. Interaction model — interaction.csv (OLS on log-ratio of redesigned to
conventional UTI/UAI vs g*).

S6. Gravity-sweep raw grid — gravity_sweep.csv; benefit_curves.csv.

S7. Negative control detail — cosmetic variants reproduce baseline mechanics
within Monte Carlo noise (door: UAI within ~3% at lunar g).

S8. Falsification criteria outcome table: criteria A–F evaluated; none
triggered rejection; benefit is gravity-specific (B≈0 at 1 g) and
cross-interface.
"""

PARETO_NOTE = """
S9. Trade-offs (Pareto). Guidance strength trades impulse suppression against
confinement/reach penalty: centering (x_free 0.05 m, η=0.8) vs guided
(x_free 0.02 m, η=0.9) — both fully suppress UTI at low g in this model, so the
choice is driven by secondary penalties rather than stability. Reported as
multi-objective summary; no scalar composite score is used.
"""


def doc_simple(path, title, paragraphs):
    d = Document()
    d.add_heading(title, level=0)
    for p in paragraphs:
        write_rich(d.add_paragraph(), p)
    d.save(path)


def build():
    # highlights
    doc_simple(os.path.join(SUB, "Highlights.docx"), "Highlights",
               [f"• {h}" for h in HIGHLIGHTS])
    # cover letter
    doc_simple(os.path.join(SUB, "CoverLetter.docx"), "Cover letter", [COVER])
    # supplement
    d = Document(); d.add_heading("Supplementary material", level=0)
    for p in SUPP_TEXT.strip().split("\n\n"):
        write_rich(d.add_paragraph(), p)
    d.add_heading("S10. Full transition table", level=1)
    tb = d.add_table(rows=len(trans)+1, cols=4); tb.style = "Table Grid"
    for j,c in enumerate(["case","variant","g*(B≥0.5)","g*(Γ_T≥1)"]):
        write_rich(tb.cell(0,j).paragraphs[0], c)
    for i,row in trans.iterrows():
        for j,v in enumerate([row.case,row.variant,
                f"{row.g_benefit50:.2f}" if pd.notna(row.g_benefit50) else "—",
                f"{row.g_baseline_Gamma1:.2f}"]):
            tb.cell(i+1,j).text = v
    write_rich(d.add_paragraph(), PARETO_NOTE)
    d.save(os.path.join(SUP, "BUILDING_ENVIRONMENT_SUPPLEMENT.docx"))
    # editable pptx figures
    prs = Presentation()
    prs.slide_width = PInches(13.333); prs.slide_height = PInches(7.5)
    names = {"fig1":"concept","fig2":"framework","fig3":"response",
             "fig4":"designs","fig5":"synthesis","fig6":"regime"}
    for k,v in names.items():
        slide = prs.slides.add_slide(prs.slide_layouts[6])
        img = os.path.join(FIG, f"{k}_{v}.png")
        slide.shapes.add_picture(img, PInches(1.5), PInches(0.4), height=PInches(4.6))
        tb_ = slide.shapes.add_textbox(PInches(0.5), PInches(5.3), PInches(12.3), PInches(2))
        tb_.text_frame.word_wrap = True
        pptx_rich(tb_.text_frame.paragraphs[0], FIGCAPS[k])
    prs.save(os.path.join(SUB, "figures_editable.pptx"))
    # tables docx
    d = Document(); d.add_heading("Tables", level=0)
    for name,df in [("S1 mc_summary",mc.head(40)),("S4 convergence",conv),
                    ("S3 sensitivity",sens),("S5 interaction",inter.round(4))]:
        d.add_heading(name, level=1)
        cols = list(df.columns)[:10]
        tb = d.add_table(rows=len(df)+1, cols=len(cols)); tb.style="Table Grid"
        for j,c in enumerate(cols): write_rich(tb.cell(0,j).paragraphs[0], str(c))
        for i,(_,row) in enumerate(df.iterrows()):
            for j,c in enumerate(cols):
                write_rich(tb.cell(i+1,j).paragraphs[0], str(row[c]))
    d.save(os.path.join(SUB, "tables.docx"))
    # figures to submission
    import shutil
    for f in os.listdir(FIG):
        shutil.copy(os.path.join(FIG,f), os.path.join(SUB,f))
    shutil.copy(os.path.join(MS,"BUILDING_ENVIRONMENT_MAIN.docx"), SUB)
    shutil.copy(os.path.join(MS,"BUILDING_ENVIRONMENT_MAIN_inline.docx"), SUB)
    shutil.copy(os.path.join(SUP,"BUILDING_ENVIRONMENT_SUPPLEMENT.docx"), SUB)
    # zip
    zpath = os.path.join(SUB, "BUILDING_ENVIRONMENT_submission_FINAL.zip")
    with zipfile.ZipFile(zpath,"w",zipfile.ZIP_DEFLATED) as z:
        for f in sorted(os.listdir(SUB)):
            if f.endswith(".zip"): continue
            z.write(os.path.join(SUB,f), f)
    print("submission package:", zpath, os.path.getsize(zpath), "bytes")


if __name__ == "__main__":
    build()
